function BubbleSim(){
  const cvRef=useRef<HTMLCanvasElement|null>(null);
  const [playing,setPlaying]=useState(true);
  const [pressure,setPressure]=useState(1.0);
  const [density,setDensity]=useState(28);
  const [drive,setDrive]=useState(0.0);
  const [feedback,setFeedback]=useState(1.0);

  const playRef=useRef(playing);
  const presRef=useRef(pressure);
  const denRef=useRef(density);
  const driveRef=useRef(drive);
  const fbRef=useRef(feedback);

  const stateRef=useRef<HTMLSpanElement|null>(null);
  const integRef=useRef<HTMLSpanElement|null>(null);
  const driftRef=useRef<HTMLSpanElement|null>(null);

  useEffect(()=>{playRef.current=playing;},[playing]);
  useEffect(()=>{presRef.current=pressure;},[pressure]);
  useEffect(()=>{denRef.current=density;},[density]);
  useEffect(()=>{driveRef.current=drive;},[drive]);
  useEffect(()=>{fbRef.current=feedback;},[feedback]);

  useEffect(()=>{
    const cv=cvRef.current; if(!cv) return;
    const ctx=cv.getContext("2d"); if(!ctx) return;
    let raf=0;
    let t=0;
    let driftPhase=0;
    const reduce=typeof window!=="undefined"&&window.matchMedia
      ? window.matchMedia("(prefers-reduced-motion: reduce)").matches : false;
    let lastW=0;

    const loop=()=>{
      const dpr=Math.min(2,window.devicePixelRatio||1);
      const w=cv.clientWidth||640,h=400;
      if(w!==lastW){cv.width=Math.round(w*dpr);cv.height=Math.round(h*dpr);lastW=w;}
      ctx.setTransform(dpr,0,0,dpr,0,0);

      const run=playRef.current&&!reduce;
      const P=presRef.current, N=Math.round(denRef.current), D=driveRef.current, FB=fbRef.current;
      if(run){ t+=0.03; driftPhase+=0.02+D*0.05; }

      const maxOff=w*0.14;
      const off=Math.sin(driftPhase)*maxOff*Math.min(1,D*1.3);

      ctx.fillStyle="#02030a"; ctx.fillRect(0,0,w,h);
      const cx=w/2+off, cy=h/2;
      const R=Math.min(w,h)*0.26;

      // stable gold-tinted interior
      const gi=ctx.createRadialGradient(cx,cy,0,cx,cy,R);
      gi.addColorStop(0,hexA(GOLD,0.16));
      gi.addColorStop(0.72,hexA(GOLD,0.05));
      gi.addColorStop(1,"transparent");
      ctx.fillStyle=gi; ctx.beginPath(); ctx.arc(cx,cy,R,0,Math.PI*2); ctx.fill();

      // per-angle gradient asymmetry: leading edge (direction of drift) compresses blue,
      // trailing edge expands violet
      const dir=Math.cos(driftPhase); // +1 leading toward right
      const leadAng=dir>=0?0:Math.PI;

      // exterior blue pressure arrows pointing inward
      const arrows=Math.max(10,Math.min(28,Math.round(N*0.8)));
      ctx.lineWidth=2;
      for(let i=0;i<arrows;i++){
        const a=(i/arrows)*Math.PI*2+t*0.15;
        // compression factor: closer to leading edge => stronger blue push
        const lead=0.5+0.5*Math.cos(a-leadAng);
        const push=P*(0.6+0.8*lead*Math.min(1,D*1.5+0.001));
        const outer=R+34+push*10+Math.sin(t*1.5+i)*3*P;
        const ox=cx+Math.cos(a)*outer, oy=cy+Math.sin(a)*outer;
        const ix=cx+Math.cos(a)*(R+10), iy=cy+Math.sin(a)*(R+10);
        ctx.strokeStyle=hexA(BLUE,0.35+0.35*lead*Math.min(1,D+0.2));
        ctx.beginPath(); ctx.moveTo(ox,oy); ctx.lineTo(ix,iy); ctx.stroke();
        // arrowhead pointing inward
        const ang=Math.atan2(iy-oy,ix-ox);
        ctx.beginPath();
        ctx.moveTo(ix,iy);
        ctx.lineTo(ix-Math.cos(ang-0.4)*6,iy-Math.sin(ang-0.4)*6);
        ctx.lineTo(ix-Math.cos(ang+0.4)*6,iy-Math.sin(ang+0.4)*6);
        ctx.closePath(); ctx.fillStyle=hexA(BLUE,0.5); ctx.fill();
      }

      // gold outward thrust arrows from the node shell
      for(let i=0;i<arrows;i++){
        const a=(i/arrows)*Math.PI*2+t*0.15+Math.PI/arrows;
        const trail=0.5+0.5*Math.cos(a-leadAng-Math.PI);
        const thrust=0.7+0.6*trail*Math.min(1,D*1.5+0.001);
        const inner=R-6, ox=cx+Math.cos(a)*(R+20*thrust), oy=cy+Math.sin(a)*(R+20*thrust);
        const ix=cx+Math.cos(a)*inner, iy=cy+Math.sin(a)*inner;
        ctx.strokeStyle=hexA(GOLD,0.3+0.3*thrust);
        ctx.lineWidth=2;
        ctx.beginPath(); ctx.moveTo(ix,iy); ctx.lineTo(ox,oy); ctx.stroke();
        const ang=Math.atan2(oy-iy,ox-ix);
        ctx.beginPath();
        ctx.moveTo(ox,oy);
        ctx.lineTo(ox-Math.cos(ang-0.4)*5,oy-Math.sin(ang-0.4)*5);
        ctx.lineTo(ox-Math.cos(ang+0.4)*5,oy-Math.sin(ang+0.4)*5);
        ctx.closePath(); ctx.fillStyle=hexA(GOLD,0.45); ctx.fill();
      }

      // violet boundary glow where forces collide (thickness modulated by asymmetry)
      for(let seg=0;seg<64;seg++){
        const a0=(seg/64)*Math.PI*2, a1=((seg+1)/64)*Math.PI*2;
        const lead=0.5+0.5*Math.cos((a0+a1)/2-leadAng);
        // leading edge thinner+bluer, trailing thicker+violet
        const bw=3+ (1-lead)*6*Math.min(1,D*1.5+0.2);
        ctx.lineWidth=bw;
        ctx.strokeStyle=hexA(VIOLET,0.4+0.35*Math.abs(Math.sin(t*2+seg*0.3)));
        ctx.beginPath();
        ctx.arc(cx,cy,R,a0,a1);
        ctx.stroke();
      }

      // node shell — pulsing with the fast feedback loop
      const pulse=0.5+0.5*Math.sin(t*(4+FB*8));
      for(let i=0;i<N;i++){
        const a=(i/N)*Math.PI*2;
        const nx=cx+Math.cos(a)*R, ny=cy+Math.sin(a)*R;
        const rad=3+pulse*2*FB;
        ctx.beginPath(); ctx.arc(nx,ny,rad+3,0,Math.PI*2);
        ctx.fillStyle=hexA(CYAN,0.2+0.2*pulse); ctx.fill();
        ctx.beginPath(); ctx.arc(nx,ny,rad,0,Math.PI*2);
        ctx.fillStyle=CYAN; ctx.shadowBlur=8*FB; ctx.shadowColor=CYAN; ctx.fill(); ctx.shadowBlur=0;
      }

      // readouts
      const drivenY=Math.min(1,D*1.3);
      const surfing=drivenY>0.12;
      const integrity=Math.max(0,Math.min(100,Math.round(100 - Math.abs(P-1)*22 - drivenY*18 + (FB-1)*10)));
      const driftVel=(drivenY*Math.cos(driftPhase)*3.2);
      if(stateRef.current) stateRef.current.textContent=surfing?"Surfing":"Stable";
      if(stateRef.current) stateRef.current.style.color=surfing?VIOLET:GREEN;
      if(integRef.current) integRef.current.textContent=integrity+" %";
      if(driftRef.current) driftRef.current.textContent=driftVel.toFixed(2)+" u/s";

      raf=requestAnimationFrame(loop);
    };
    raf=requestAnimationFrame(loop);
    return ()=>cancelAnimationFrame(raf);
  },[]);

  const slider=(label:string,val:number,set:(n:number)=>void,min:number,max:number,step:number,col:string,fmt:(n:number)=>string)=>(
    <div style={{marginBottom:10}}>
      <div style={{display:"flex",justifyContent:"space-between",fontFamily:"monospace",fontSize:11,color:MUTED,marginBottom:4}}>
        <span style={{color:col}}>{label}</span><span style={{color:TEXT}}>{fmt(val)}</span>
      </div>
      <input type="range" min={min} max={max} step={step} value={val} onChange={e=>set(parseFloat(e.target.value))}
        style={{width:"100%",accentColor:col}}/>
    </div>
  );

  return(
    <div style={{display:"grid",gridTemplateColumns:"repeat(auto-fit,minmax(300px,1fr))",gap:16}}>
      <div>
        <canvas ref={cvRef} style={{width:"100%",height:400,display:"block",borderRadius:12,border:`1px solid ${BORDER}`,background:"#02030a"}}/>
        <div style={{display:"flex",gap:16,marginTop:10,flexWrap:"wrap",fontFamily:"monospace",fontSize:11,color:MUTED}}>
          <span style={{display:"flex",alignItems:"center",gap:6}}><span style={{width:10,height:10,borderRadius:"50%",background:BLUE}}/>external pressure</span>
          <span style={{display:"flex",alignItems:"center",gap:6}}><span style={{width:10,height:10,borderRadius:"50%",background:GOLD}}/>node thrust / interior</span>
          <span style={{display:"flex",alignItems:"center",gap:6}}><span style={{width:10,height:10,borderRadius:"50%",background:VIOLET}}/>boundary</span>
          <span style={{display:"flex",alignItems:"center",gap:6}}><span style={{width:10,height:10,borderRadius:"50%",background:CYAN}}/>nodes</span>
        </div>
        <div style={{display:"flex",justifyContent:"center",marginTop:12}}>
          <button onClick={()=>setPlaying(p=>!p)}
            style={{display:"flex",alignItems:"center",gap:8,padding:"9px 18px",background:hexA(VIOLET,0.18),color:VIOLET,border:`1px solid ${hexA(VIOLET,0.4)}`,borderRadius:8,cursor:"pointer",fontFamily:"monospace",fontSize:12}}>
            {playing?<Pause size={16}/>:<Play size={16}/>}{playing?"Pause":"Play"}
          </button>
        </div>
      </div>
      <div style={{display:"flex",flexDirection:"column",gap:14}}>
        <div style={{background:PAN2,border:`1px solid ${BORDER}`,borderRadius:12,padding:16}}>
          <div style={{fontFamily:"monospace",fontSize:11,color:CYAN,textTransform:"uppercase",letterSpacing:1,marginBottom:12}}>Controls</div>
          {slider("External Pressure",pressure,setPressure,0.2,2,0.05,BLUE,v=>v.toFixed(2)+"×")}
          {slider("Node Density",density,setDensity,10,48,1,CYAN,v=>Math.round(v)+" nodes")}
          {slider("Motion Drive",drive,setDrive,0,1,0.02,VIOLET,v=>Math.round(v*100)+"%")}
          {slider("Feedback Rate",feedback,setFeedback,0.5,2,0.05,GOLD,v=>(v*1000).toFixed(0)+" Hz")}
        </div>
        <div style={{background:PAN2,border:`1px solid ${BORDER}`,borderRadius:12,padding:16}}>
          <div style={{fontFamily:"monospace",fontSize:11,color:GOLD,textTransform:"uppercase",letterSpacing:1,marginBottom:12}}>Readouts</div>
          <div style={{display:"flex",justifyContent:"space-between",fontFamily:"monospace",fontSize:12,color:MUTED,marginBottom:8}}>
            <span>Equilibrium</span><span ref={stateRef} style={{color:GREEN}}>Stable</span>
          </div>
          <div style={{display:"flex",justifyContent:"space-between",fontFamily:"monospace",fontSize:12,color:MUTED,marginBottom:8}}>
            <span>Boundary Integrity</span><span ref={integRef} style={{color:TEXT}}>100 %</span>
          </div>
          <div style={{display:"flex",justifyContent:"space-between",fontFamily:"monospace",fontSize:12,color:MUTED}}>
            <span>Drift Velocity</span><span ref={driftRef} style={{color:TEXT}}>0.00 u/s</span>
          </div>
        </div>
        <div style={{background:PAN2,border:`1px solid ${BORDER}`,borderRadius:12,padding:16}}>
          <div style={{fontSize:12,color:MUTED,lineHeight:1.6}}>
            Blue arrows are the inward external field; gold arrows are the shell's outward thrust; the violet ring is the boundary where they collide. Raise <span style={{color:VIOLET}}>Motion Drive</span> to shift equilibrium — the leading edge compresses (blue) while the trailing edge expands (violet) and the bubble surfs its own field.
          </div>
        </div>
      </div>
    </div>
  );
}

